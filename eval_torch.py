def plot_pointclouds_2D(
    generated_samples: np.ndarray, 
    true_samples: np.ndarray, 
    idx_to_plot: int = 0
):
    """Plot pointcloud in two dimensions.
    
    Args:
        generated_samples: Samples generated by the model (numpy array)
        true_samples: True samples (numpy array)
        idx_to_plot: Index to plot
        
    Returns:
        plt.figure: figure
    """
    s = 4
    alpha = 0.5
    color = "firebrick"
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(20, 12))
    
    ax1.scatter(
        generated_samples[idx_to_plot, :, 0],
        generated_samples[idx_to_plot, :, 1],
        alpha=alpha,
        s=s,
        color=color,
    )
    ax1.set_title("Generated")
    ax1.set_xlabel("x")
    ax1.set_ylabel("y")
    
    ax2.scatter(
        true_samples[idx_to_plot, :, 0],
        true_samples[idx_to_plot, :, 1],
        alpha=alpha,
        s=s,
        color=color,
    )
    ax2.set_title("True")
    ax2.set_xlabel("x")
    ax2.set_ylabel("y")
    
    return fig


def eval_likelihood(
    vdm: VariationalDiffusionModel,
    state_dict: dict,
    true_samples: torch.Tensor,
    conditioning: torch.Tensor,
    mask: torch.Tensor,
    device: str = 'cuda',
):
    """Evaluate likelihood for samples.
    
    Args:
        vdm: Variational diffusion model
        state_dict: Model state dictionary
        true_samples: True samples (batch, n_particles, n_features)
        conditioning: Conditioning context (batch, n_cond)
        mask: Mask (batch, n_particles)
        device: Device to run on
    """
    vdm.load_state_dict(state_dict)
    vdm.to(device)
    vdm.eval()
    
    with torch.no_grad():
        true_samples = true_samples.to(device)
        if conditioning is not None:
            conditioning = conditioning.to(device)
        mask = mask.to(device)
        
        # Compute losses
        loss_diff, loss_klz, loss_recon = vdm(true_samples, conditioning, mask)
        
        # Compute total loss with masking
        if mask is None:
            mask = torch.ones(true_samples.shape[:-1], device=device)
        
        loss_batch = (
            ((loss_diff + loss_klz) * mask[:, :, None]).sum((-1, -2)) +
            (loss_recon * mask[:, :, None]).sum((-1, -2))
        ) / mask.sum(-1)
        
        loss = loss_batch.mean()
    
    # Log to wandb if available
    try:
        wandb.log({
            'eval/likelihood': -loss.item(),
            'eval/loss': loss.item(),
        })
    except:
        pass
    
    print(f"Evaluation likelihood: {-loss.item():.4f}")
    print(f"Evaluation loss: {loss.item():.4f}")
    
    return loss.item()


def eval_generation(
    vdm: VariationalDiffusionModel,
    state_dict: dict,
    n_samples: int,
    n_particles: int,
    true_samples: torch.Tensor = None,
    conditioning: torch.Tensor = None,
    mask: torch.Tensor = None,
    norm_dict: dict = None,
    steps: int = 500,
    boxsize: float = 1000.0,
    device: str = 'cuda',
):
    """Evaluate generation quality.
    
    Args:
        vdm: Variational diffusion model
        state_dict: Model state dictionary
        n_samples: Number of samples to generate
        n_particles: Number of particles per sample
        true_samples: True samples for comparison (optional)
        conditioning: Conditioning context
        mask: Mask
        norm_dict: Normalization dictionary
        steps: Number of diffusion steps
        boxsize: Size of simulation box
        device: Device to run on
    """
    vdm.load_state_dict(state_dict)
    vdm.to(device)
    vdm.eval()
    
    print(f"Generating {n_samples} samples with {n_particles} particles...")
    
    with torch.no_grad():
        # Generate samples
        if conditioning is not None:
            conditioning = conditioning.to(device)
        if mask is not None:
            mask = mask.to(device)
        
        samples_dist = generate(
            vdm,
            shape=(n_samples, n_particles),
            conditioning=conditioning,
            mask=mask,
            steps=steps,
            device=device,
        )
        
        # Get mean of distribution
        generated_samples = samples_dist.mean
        
        # Convert to numpy for plotting/analysis
        generated_samples_np = generated_samples.cpu().numpy()
        
        # Denormalize if norm_dict is provided
        if norm_dict is not None:
            mean = np.array(norm_dict['mean'])
            std = np.array(norm_dict['std'])
            generated_samples_np = generated_samples_np * std + mean
    
    print(f"Generated samples shape: {generated_samples_np.shape}")
    
    # Plot if true samples are provided
    if true_samples is not None:
        true_samples_np = true_samples.cpu().numpy()
        
        # Denormalize true samples
        if norm_dict is not None:
            true_samples_np = true_samples_np * std + mean
        
        # Plot comparison
        fig = plot_pointclouds_2D(generated_samples_np, true_samples_np, idx_to_plot=0)
        
        # Log to wandb if available
        try:
            wandb.log({"eval/samples_comparison": wandb.Image(fig)})
        except:
            pass
        
        plt.close(fig)
    
    return generated_samples_np


def generate_samples(
    vdm: VariationalDiffusionModel,
    state_dict: dict,
    n_samples: int,
    n_particles: int,
    conditioning: torch.Tensor = None,
    mask: torch.Tensor = None,
    steps: int = 500,
    device: str = 'cuda',
) -> np.ndarray:
    """Generate samples from the model.
    
    Args:
        vdm: Variational diffusion model
        state_dict: Model state dictionary
        n_samples: Number of samples to generate
        n_particles: Number of particles per sample
        conditioning: Conditioning context (batch, n_cond)
        mask: Mask (batch, n_particles)
        steps: Number of diffusion steps
        device: Device to run on
        
    Returns:
        Generated samples as numpy array
    """
    vdm.load_state_dict(state_dict)
    vdm.to(device)
    vdm.eval()
    
    with torch.no_grad():
        if conditioning is not None:
            conditioning = conditioning.to(device)
        if mask is not None:
            mask = mask.to(device)
        
        samples_dist = generate(
            vdm,
            shape=(n_samples, n_particles),
            conditioning=conditioning,
            mask=mask,
            steps=steps,
            device=device,
        )
        
        samples = samples_dist.mean.cpu().numpy()
    
    return samples


def generate_test_samples_from_checkpoint(
    checkpoint_path: str,
    n_samples: int,
    n_particles: int,
    n_features: int,
    conditioning: torch.Tensor = None,
    steps: int = 500,
    device: str = 'cuda',
) -> np.ndarray:
    """Generate samples from a saved checkpoint.
    
    Args:
        checkpoint_path: Path to checkpoint file
        n_samples: Number of samples to generate
        n_particles: Number of particles
        n_features: Number of features
        conditioning: Conditioning context
        steps: Number of diffusion steps
        device: Device to run on
        
    Returns:
        Generated samples
    """
    # Load checkpoint
    checkpoint = torch.load(checkpoint_path, map_location=device)
    config = checkpoint['config']
    
    # Create model
    from models.diffusion_torch import VariationalDiffusionModel
    
    score_dict = config['score']
    encoder_dict = config.get('encoder', {})
    decoder_dict = config.get('decoder', {})
    
    norm_dict_input = {
        "x_mean": tuple(map(float, checkpoint.get('norm_dict', {}).get('mean', [0.0] * n_features))),
        "x_std": tuple(map(float, checkpoint.get('norm_dict', {}).get('std', [1.0] * n_features))),
        "box_size": config['data']['box_size'],
    }
    
    vdm = VariationalDiffusionModel(
        d_feature=n_features,
        timesteps=config['vdm']['timesteps'],
        noise_schedule=config['vdm']['noise_schedule'],
        noise_scale=config['vdm']['noise_scale'],
        d_t_embedding=config['vdm']['d_t_embedding'],
        gamma_min=config['vdm']['gamma_min'],
        gamma_max=config['vdm']['gamma_max'],
        score=config['score']['score'],
        score_dict=score_dict,
        embed_context=config['vdm']['embed_context'],
        d_context_embedding=config['vdm']['d_context_embedding'],
        n_classes=config['vdm']['n_classes'],
        use_encdec=config['vdm']['use_encdec'],
        encoder_dict=encoder_dict,
        decoder_dict=decoder_dict,
        norm_dict=norm_dict_input,
    ).to(device)
    
    # Load state
    vdm.load_state_dict(checkpoint['model_state_dict'])
    
    # Generate samples
    samples = generate_samples(
        vdm=vdm,
        state_dict=checkpoint['model_state_dict'],
        n_samples=n_samples,
        n_particles=n_particles,
        conditioning=conditioning,
        steps=steps,
        device=device,
    )
    
    return samples
